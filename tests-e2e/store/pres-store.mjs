const FRONT = "/home/joshua/rust/audio/front";
const { createServer } = await import(FRONT + "/node_modules/vite/dist/node/index.js");
const mem = new Map();
globalThis.localStorage = { getItem: (k) => mem.get(k) ?? null, setItem: (k, v) => mem.set(k, v), removeItem: (k) => mem.delete(k) };
const vite = await createServer({ root: FRONT, configFile: FRONT + "/vite.config.ts", server: { middlewareMode: true }, appType: "custom", logLevel: "error" });
const { ChatStore, isShownOnline } = await vite.ssrLoadModule("/src/chat/store.ts");
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
async function until(f, what, ms = 5000) { for (let t = 0; t < ms; t += 25) { if (f()) return; await sleep(25); } console.log("ÉCHEC (timeout)", what); process.exit(1); }
const ok = (c, m) => { if (!c) { console.log("ÉCHEC", m); process.exit(1); } console.log("ok", m); };
const s = (x) => x.getSnapshot();
const t = (n) => `00000000-0000-0000-0000-00000000000${n}`;
const B = new ChatStore(t(2)); B.start(); await until(() => s(B).phase === "pseudo", "B"); await B.setPseudo("Bob");
const A = new ChatStore(t(1)); A.start(); await until(() => s(A).phase === "pseudo", "A"); await A.setPseudo("Léa");
const aId = s(A).me.id;
ok(isShownOnline(s(A), aId) && !s(A).me.invisible, "A se voit en ligne tout de suite");
ok(!isShownOnline(s(B), aId), "B ne voit pas encore A");
await until(() => isShownOnline(s(B), aId), "B voit A en ligne après le délai");
ok(true, "B voit A en ligne après le délai");
await A.setInvisible(true);
ok(s(A).me.invisible && !isShownOnline(s(A), aId), "A invisible (se voit hors ligne)");
await until(() => !isShownOnline(s(B), aId), "B voit A hors ligne");
ok(true, "B voit A hors ligne tout de suite");
A.dispose();
const A2 = new ChatStore(t(1)); A2.start(); await until(() => s(A2).phase === "ready", "A2");
ok(s(A2).me.invisible, "invisible mémorisé à la reconnexion");
await sleep(1200); ok(!isShownOnline(s(B), aId), "A2 invisible jamais annoncé");
await A2.setInvisible(false); await until(() => isShownOnline(s(B), aId), "A2 en ligne");
ok(true, "repasser en ligne : annoncé tout de suite");
const C = new ChatStore(t(3)); C.start(); await until(() => s(C).phase === "pseudo", "C");
ok(isShownOnline(s(C), aId) && isShownOnline(s(C), s(B).me.id), "nouvel arrivant : état initial depuis online_user_ids");
A2.dispose(); B.dispose(); C.dispose(); await vite.close(); process.exit(0);
