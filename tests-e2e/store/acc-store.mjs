import { readFileSync } from "node:fs";
const FRONT = "/home/joshua/rust/audio/front";
const { createServer } = await import(FRONT + "/node_modules/vite/dist/node/index.js");
const mem = new Map();
globalThis.localStorage = { getItem: (k) => mem.get(k) ?? null, setItem: (k, v) => mem.set(k, v), removeItem: (k) => mem.delete(k) };
globalThis.window = { matchMedia: () => ({ matches: false, addEventListener() {} }), location: { origin: "x" }, addEventListener() {}, removeEventListener() {} };
globalThis.document = { hidden: false, hasFocus: () => false, addEventListener() {}, removeEventListener() {}, documentElement: { classList: { toggle() {} }, style: {} } };
const vite = await createServer({ root: FRONT, configFile: FRONT + "/vite.config.ts", server: { middlewareMode: true }, appType: "custom", logLevel: "error" });
const { ChatStore } = await vite.ssrLoadModule("/src/chat/store.ts");
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
async function until(f, what, ms = 5000) { for (let t = 0; t < ms; t += 25) { if (f()) return; await sleep(25); } console.log("ÉCHEC (timeout)", what); process.exit(1); }
const ok = (c, m) => { if (!c) { console.log("ÉCHEC", m); process.exit(1); } console.log("ok", m); };
const s = (x) => x.getSnapshot();
const boot = /\/\?invite=(\S+)/.exec(readFileSync(process.argv[2], "utf8"))[1];
const A = new ChatStore(null, boot); A.start();
await until(() => s(A).phase === "login", "écran");
await until(() => s(A).inviteValid !== null, "vérification de l'invitation");
ok(s(A).invite === boot && s(A).inviteValid === true, "lien d'invitation vérifié : écran de création de compte");
await A.acceptInvite("admin@x.fr", "Léa", "court");
ok(s(A).phase === "login" && s(A).error && s(A).invite, "mot de passe trop court : erreur, on reste sur l'invitation");
await A.acceptInvite("admin@x.fr", "Léa", "motdepasse-admin");
ok(s(A).phase === "ready" && s(A).me.isAdmin && s(A).me.hasPassword && !s(A).invite, "compte admin créé, directement dans le chat (pseudo déjà choisi)");
const invite = await A.createInvite(3600);
ok(invite?.token && (await A.listInvites()).length === 1, "admin : invitation créée et listée");
const revoked = await A.createInvite(3600);
await A.revokeInvite(revoked.token);
mem.clear(); // R : navigateur sans session
const R = new ChatStore(null, revoked.token); R.start();
await until(() => s(R).inviteValid !== null, "vérification de l'invitation révoquée");
ok(s(R).inviteValid === false && s(R).phase === "login", "lien révoqué : « plus valable », pas de formulaire");
R.dispose();
mem.clear();
const B = new ChatStore(null, invite.token); B.start(); await until(() => s(B).phase === "login", "B");
await B.acceptInvite("bob@x.fr", "Bob", "motdepasse-bob");
ok(s(B).phase === "ready" && s(B).me.pseudo === "Bob", "Bob s'inscrit avec l'invitation");
B.logout(); await until(() => s(B).phase === "login", "logout");
await B.loginWithPassword("bob@x.fr", "pas-le-bon");
ok(s(B).phase === "login" && s(B).error === "email ou mot de passe incorrect", "mauvais mot de passe : erreur générique");
await B.loginWithPassword("bob@x.fr", "motdepasse-bob");
ok(s(B).phase === "ready", "connexion email + mot de passe");
ok(await B.setPassword("motdepasse-bob", "nouveau-mdp-bob"), "mot de passe changé depuis le profil");
const link = await A.createLoginLink(s(B).me.id, 900);
ok(link?.token, "admin : lien de connexion pour Bob");
ok(await A.revokeInvite((await A.createInvite(3600)).token), "admin : révocation");
for (const x of [A, B]) x.dispose(); await vite.close(); process.exit(0);
